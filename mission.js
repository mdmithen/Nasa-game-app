/* ============================================================
   PHASE 3 - MISSION PREPARATION AND SURVIVAL SIMULATION
   ------------------------------------------------------------
   Two things live here, and neither of them existed before Phase 3:

     1. THE PRE-FLIGHT CHECK. Before a mission can launch, the base is
        checked against what it needs: every structure a crew cannot
        live without, and the supplies it has to depart with. Anything
        missing is listed by name, so the panel says what to build
        rather than just refusing.

     2. THE DAILY SURVIVAL CYCLE. Until now the daily numbers were
        fixed constants, so the landing site and the base the player
        spent the whole builder designing had no effect at all. Here
        the base is read for what it actually provides, the site is
        read for what it actually gives you, and the two are combined
        into the day's consumption and production.

   HONESTY NOTE, AND IT MATTERS
   -----------------------------
   Every number in this file is a GAME ESTIMATE. None of it is a NASA
   measurement, a mission-planning figure, or a claim about what a real
   lunar base would consume. The real science lives in sites.js under
   facts[], and the line between the two never moves.

     GAME ESTIMATE  consumption, production, wear, cargo, and the
                    thresholds a base must clear to launch.

     REAL SCIENCE   oxygen, water, food, power, dust and the polar day
                    and night cycle are all real problems. The
                    magnitudes used here are invented to keep them
                    teachable.

   The one thing this file must never do is let the mission state drift:
   no resource may go negative, no condition may leave 0-100, and no
   objective may be marked done unless it genuinely is. `sanitizeMission`
   enforces all three and is called after anything that changes state.
   ============================================================ */

/* ------------------------------------------------------------
   1. PHASE 3 GAME VALUES
   All GAME ESTIMATE. See the honesty note above.
   ------------------------------------------------------------ */

/* How well a system is working, as a percentage. 100 is brand new.
   Output is scaled by this number, so a worn machine really does
   deliver less rather than just being described as worn. */
var MAINT_START = 100;

/* How much condition a system loses per day before the site's dust is
   taken into account. Higher at a dusty site, because real lunar dust
   gets into seals, scratches glass and jams filters - one of the
   hardest problems for any lunar base, and a documented one.

   Tuned so that a base that is serviced keeps ahead of the wear, and a
   base that is ignored at a dusty site does not. That gap is the whole
   point of the maintenance model: at Tycho, which is the dustiest site
   on the map, a single solar array with one depot crosses the failure
   line around mission day 13. */
var MAINT_BASE_WEAR = 3;
var MAINT_DUST_WEAR = 6;

/* Each supply depot holds spares, so it slows wear on everything else.
   One depot is worth this much, and more depots help but with
   diminishing returns. */
var MAINT_SPARES_PER_DEPOT = 0.6;

/* Below this condition a system is called failed rather than worn.
   A failed system still runs, but badly, and the crew notices. */
var MAINT_FAIL_LEVEL = 35;

/* What each structure contributes, per day, at full condition.
   These are the numbers that make the layout matter. A base with no
   oxygen system scrubs nothing; a base with two of them is not allowed
   to build two, because the second would be wasted. */
var CAPABILITY_VALUES = {
  solar:     22,    /* power generated by one full, healthy array   */
  oxygen:     4,    /* oxygen scrubbed back into the cabin        */
  water:      4,    /* clean water returned by the recycler       */
  food:       3,    /* food grown by the hydroponics              */
  habitat:    3,    /* crew health recovered by a proper night's  */
                /* rest in a pressurized habitat                 */
  depot:      2,    /* supplies opened each day by a stocked depot*/
  console:    1,    /* planning credit: better warning of trouble */
  pad:        2     /* cargo handling: deliveries and departure   */
};

/* The solar figure above is the fallback. The single source of truth
   is SOLAR_GENERATION in script.js, which is read at runtime so the
   two can never drift apart. */
function solarGeneration() {
  return (typeof SOLAR_GENERATION === 'number') ? SOLAR_GENERATION : CAPABILITY_VALUES.solar;
}

/* Extra solar arrays are worth less than the first one, because one
   good array already covers the base and the rest are surplus. */
var CAPABILITY_SOLAR_STEP = 0.5;

/* Heating costs power. A warm site needs less of it. */
var HEATING_POWER_COST = 4;

/* Ice-rich ground means the recycler has good raw material, so the
   water recycler returns more. Scaled by the site's ice figure. */
var ICE_WATER_BONUS = 4;

/* Supplies a crew must be able to live on. These are checked before
   launch and shown in the pre-flight list. */
var PREFLIGHT_MIN_STORES = {
  oxygen: 60,
  water:  55,
  food:   55,
  power:  60,
  health: 70
};

/* How many surface canisters and structure types a crew must survey
   before the science objectives are signed off. */
var EXPLORE_TARGET = 6;
var SURVEY_TARGET = 4;

/* ------------------------------------------------------------
   2. THE PRE-FLIGHT CHECK
   Two kinds of requirement, both listed with a reason:

     structures  every type a crew cannot do without
     supplies    the stores the crew must depart with, and whether
                 the base can actually keep them up

   The balance figures are a projection, not a promise. They use the
   same maths as the real daily cycle, run against the site that is
   about to be chosen, so a player who is about to build somewhere the
   Sun barely reaches is told so before they commit.
   ------------------------------------------------------------ */

/* Every structure type is required. There is no way to run a lunar
   base without air, water, food, power somewhere to sleep, somewhere
   to work, somewhere to land, or somewhere to keep spares. */
function preflightRequiredTypes() {
  if (typeof STATION_TYPES !== 'undefined') { return STATION_TYPES; }
  return [];
}

function preflightChecklist() {
  var items = [];
  var types = preflightRequiredTypes();

  /* ---- required structures ---- */
  for (var i = 0; i < types.length; i++) {
    var t = types[i];
    var have = countOfType(t.id);
    items.push({
      kind: 'structure',
      id: 'structure-' + t.id,
      label: t.name,
      ok: have > 0,
      detail: have > 0
        ? 'Built - ' + t.role
        : 'Not built - ' + t.role
    });
  }

  /* ---- supplies the crew departs with ----
     Read from the live mission only while one is actually running. A
     finished mission leaves the old day's numbers behind in `game`,
     and a pre-flight check must never be judging the last mission's
     leftovers. Before a mission, the crew departs with full stores. */
  var liveMission = game && !game.finished;
  var keys = ['oxygen', 'water', 'food', 'power', 'health'];
  for (var k = 0; k < keys.length; k++) {
    var key = keys[k];
    var need = PREFLIGHT_MIN_STORES[key];
    var have = (liveMission && typeof game[key] === 'number' && !isNaN(game[key]))
      ? game[key] : MAX_VALUE;
    items.push({
      kind: 'supply',
      id: 'supply-' + key,
      label: (RESOURCES[key] ? RESOURCES[key].name : key) + ' in store',
      ok: have >= need,
      detail: 'Have ' + Math.round(have) + ', need at least ' + need
    });
  }

  /* ---- can the base keep those stores up at this site? ---- */
  var plan = missionProjectedDaily();
  var vital = ['oxygen', 'water', 'food', 'power'];
  for (var v = 0; v < vital.length; v++) {
    var r = vital[v];
    var delta = plan[r];
    var days = (delta < 0) ? Math.floor(100 / -delta) : null;
    var survives = (delta >= 0) || (days >= MISSION_LENGTH_DAYS);

    /* Only quote a day number when it lands inside the mission.
       "empty by about day 166" is arithmetic that means nothing to a
       player who only has 16 of them. */
    var detail;
    if (delta >= 0) {
      detail = (delta > 0 ? '+' : '') + round1(delta) + ' a day - the stores hold';
    } else if (survives) {
      detail = round1(delta) + ' a day - the stores outlast the ' +
               MISSION_LENGTH_DAYS + ' day mission';
    } else {
      detail = round1(delta) + ' a day - empty by about day ' + days;
    }

    items.push({
      kind: 'balance',
      id: 'balance-' + r,
      label: 'Daily ' + (RESOURCES[r] ? RESOURCES[r].name.toLowerCase() : r) + ' balance',
      ok: survives,
      warn: delta < 0 && survives,
      detail: detail
    });
  }

  /* ---- what the published record says about this crater ----
     Not a requirement: nothing here blocks a launch. It is here so
     the mission-preparation panel shows the same evidence the map
     did, at the moment the player commits to the site. */
  var zone = (typeof zoneById === 'function') ? zoneById(game && game.zoneId) : null;
  if (zone && typeof lunarSiteData === 'function') {
    var rec = lunarSiteData(zone.id);

    if (rec && rec.crater) {
      items.push({
        kind: 'science',
        id: 'science-crater',
        label: 'Crater size (measured)',
        ok: true,
        detail: rec.crater.name + ' is ' + rec.crater.diameterKm +
          ' km across - VERIFIED, ' + sourceShort(rec.crater.sourceId)
      });
    }

    if (rec && rec.ice) {
      var iceText = {
        detected: 'Water ice was measured here directly',
        cluster: 'Ice was detected in the neighbourhood',
        'not-detected': 'No ice has been detected at this crater',
        'out-of-band': 'Too far from the pole for ice to survive'
      }[rec.ice.status] || 'Ice status unknown';
      items.push({
        kind: 'science',
        id: 'science-ice',
        ok: true,
        label: 'Water ice (measured)',
        detail: iceText + ' - VERIFIED, ' + sourceShort(rec.ice.sourceId)
      });
    }

    if (typeof surveyTargetFor === 'function') {
      var need = surveyTargetFor(zone.id);
      var usual = (typeof SURVEY_TARGET_DEFAULT === 'number') ? SURVEY_TARGET_DEFAULT : 4;
      items.push({
        kind: 'science',
        id: 'science-survey',
        ok: true,
        label: 'Science survey target',
        detail: 'Inspect ' + need + ' structures' +
          (need !== usual
            ? ' instead of ' + usual + ', because ice was actually measured here.'
            : '.')
      });
    }
  }

  return items;
}

/* The short name of a source, for a one-line citation. */
function sourceShort(id) {
  var src = (typeof lunarSource === 'function') ? lunarSource(id) : null;
  return src ? src.short : 'source unknown';
}

function preflightMissing() {
  var all = preflightChecklist();
  var missing = [];
  for (var i = 0; i < all.length; i++) {
    if (!all[i].ok) { missing.push(all[i]); }
  }
  return missing;
}

/* Only a hard block stops a launch. A negative-but-survivable balance
   is reported as a warning, because sometimes that is a deliberate and
   interesting choice - it just has to be an informed one. */
function preflightReady() {
  return preflightMissing().length === 0;
}

/* ------------------------------------------------------------
   3. WHAT THE BASE AND THE SITE ACTUALLY PROVIDE
   ------------------------------------------------------------ */

/* The base the mission will actually be played on.
   While the builder is open that is what is in the builder, NOT what
   the last mission left behind in `game`. Reading `game.layout` during
   the pre-flight check made every structure look missing on a fresh
   page, because `game` still holds the starting game object. */
function missionLayout() {
  if (typeof builder !== 'undefined' && builder && builder.open) {
    return builder.layout || [];
  }
  return (game && game.layout) ? game.layout : [];
}

function countOfType(type) {
  var layout = missionLayout();
  var n = 0;
  for (var i = 0; i < layout.length; i++) {
    if (layout[i].type === type) { n++; }
  }
  return n;
}

/* Everything the built base contributes, before the site is applied. */
function baseCapabilities() {
  var caps = {
    solarPanels: countOfType('solar'),
    depots: countOfType('depot'),
    hasHabitat: countOfType('habitat') > 0,
    hasOxygen: countOfType('oxygen') > 0,
    hasWater: countOfType('water') > 0,
    hasFood: countOfType('food') > 0,
    hasConsole: countOfType('console') > 0,
    hasPad: countOfType('pad') > 0,
    solar: 0, oxygen: 0, water: 0, food: 0, health: 0, supplies: 0, planning: 0
  };

  /* One array does the job; each extra one adds half as much again,
     because past the first the base is already covered. */
  caps.solar = solarGeneration() *
    (1 + CAPABILITY_SOLAR_STEP * (caps.solarPanels - 1));

  caps.oxygen = caps.hasOxygen ? CAPABILITY_VALUES.oxygen : 0;
  caps.water = caps.hasWater ? CAPABILITY_VALUES.water : 0;
  caps.food = caps.hasFood ? CAPABILITY_VALUES.food : 0;
  caps.health = caps.hasHabitat ? CAPABILITY_VALUES.habitat : 0;
  caps.supplies = CAPABILITY_VALUES.depot * caps.depots;
  caps.planning = caps.hasConsole ? CAPABILITY_VALUES.console : 0;

  /* A crew with nowhere to land cannot be resupplied or go home, so a
     base without a pad gets no supply deliveries either. */
  if (!caps.hasPad) { caps.supplies = 0; }

  return caps;
}

/* The landing site's contribution. Every one of these is a GAME
   ESTIMATE from sites.js, read through the neutral set when no site
   was chosen, so a mission with no map still plays exactly the same. */
function siteFactors() {
  var zone = (typeof zoneById === 'function') ? zoneById(game && game.zoneId) : null;
  var mods = (typeof zoneModsFor === 'function') ? zoneModsFor(zone) : null;

  if (!mods) {
    mods = { sunlight: 1, powerBonus: 1, ice: 0, dust: 0.5, heat: 0.5 };
  }

  return {
    zone: zone,

    /* Real science underneath: at the poles the Sun circles the
       horizon, and inside a permanently shadowed crater it never
       arrives at all. The floor keeps a little light so a base there
       is hard rather than impossible, and the ceiling keeps a sunny
       rim from beating the original figure the game was balanced on. */
    sun: clamp((0.52 + 0.55 * mods.sunlight) * (0.8 + 0.2 * mods.powerBonus), 0, 1),

    /* Warm ground needs less power spent on heating. */
    heating: (1 - mods.heat) * HEATING_POWER_COST,

    /* Ice-rich ground gives the recycler better raw material. */
    iceWater: mods.ice * ICE_WATER_BONUS,

    /* Dust is the real enemy of seals, panels and filters. */
    dust: mods.dust
  };
}

/* How worn a system is right now, as a plain 0-100 number.

   During the builder this reports brand new equipment, because `game`
   still holds the previous mission's state and a pre-flight forecast
   has to describe the mission the player is about to play, not the one
   they just finished. A mission always starts with everything at 100. */
function conditionOf(system) {
  if (typeof builder !== 'undefined' && builder && builder.open) { return MAINT_START; }
  if (!game || !game.maint || typeof game.maint[system] !== 'number') { return MAINT_START; }
  return game.maint[system];
}

/* The permanent modifiers the day cycle runs on. Same reasoning as
   conditionOf: a forecast starts from untouched systems. */
function missionMods() {
  if (typeof builder !== 'undefined' && builder && builder.open) {
    return {
      solarFactor: 1, solarFactorUntilDay: 0, stormSolarFactor: 1,
      waterRecovery: 0, oxygenProduction: 0, foodProduction: 0, extraFoodUse: 0
    };
  }
  return (game && game.mods) ? game.mods : {};
}

/* The mission day the cycle is thinking about. Day 1 before a mission
   has started, so a leftover day 14 from the last attempt cannot make
   the forecast think a storm is still blowing. */
function missionDay() {
  if (typeof builder !== 'undefined' && builder && builder.open) { return 1; }
  return (game && typeof game.day === 'number') ? game.day : 1;
}

/* A system below MAINT_FAIL_LEVEL still runs, but badly. This is the
   "life support failure" the crew has to notice and fix. */
function systemFailed(system) {
  return conditionOf(system) < MAINT_FAIL_LEVEL;
}

/* Output is scaled by condition, and a failed system is scaled again
   because worn parts do not simply work a bit less well, they work
   badly and unpredictably. */
function outputFactor(system) {
  var f = conditionOf(system) / MAINT_START;
  if (systemFailed(system)) { f = f * 0.5; }
  return f;
}

/* ------------------------------------------------------------
   4. EQUIPMENT MAINTENANCE
   ------------------------------------------------------------ */

function missionNewState() {
  return {
    maint: {
      solar: MAINT_START,
      oxygen: MAINT_START,
      water: MAINT_START,
      food: MAINT_START,
      habitat: MAINT_START
    },
    faults: {},            /* system -> true once it has failed outright */
    pendingEmergency: null, /* system waiting for its emergency scenario   */
    explored: 0,           /* canisters collected, for the science task  */
    surveyed: {},          /* structure types inspected, for the survey   */
    lastBalance: null,     /* yesterday's numbers, shown on the report    */
    storms: 0              /* how many dust storms this mission has seen  */
  };
}

/* Spares slow wear. Without them a dusty site grinds the base down and
   the player has to spend days servicing things they would rather not. */
function dailyWear(system, factors, caps) {
  var spares = 1 + MAINT_SPARES_PER_DEPOT * caps.depots;
  var dustWear = MAINT_BASE_WEAR + MAINT_DUST_WEAR * factors.dust;

  var rate = dustWear / spares;

  /* A system that is not in the base has nothing to wear out. */
  if (!systemBuilt(system)) { rate = 0; }
  return rate;
}

function systemBuilt(system) {
  var caps = baseCapabilities();
  if (system === 'solar')    { return caps.solarPanels > 0; }
  if (system === 'oxygen')   { return caps.hasOxygen; }
  if (system === 'water')    { return caps.hasWater; }
  if (system === 'food')     { return caps.hasFood; }
  if (system === 'habitat')  { return caps.hasHabitat; }
  return false;
}

/* Wear everything down by one day. Called once per day, after the
   day's production has already been worked out, so a repair today
   helps tomorrow rather than today. */
function wearDownDay() {
  var caps = baseCapabilities();
  var factors = siteFactors();
  var log = [];

  for (var i = 0; i < MAINT_SYSTEMS.length; i++) {
    var system = MAINT_SYSTEMS[i];
    var wear = dailyWear(system, factors, caps);
    if (wear <= 0) { continue; }

    var before = conditionOf(system);
    var after = clamp(before - wear, 0, MAINT_START);
    game.maint[system] = round1(after);

    if (before >= MAINT_FAIL_LEVEL && after < MAINT_FAIL_LEVEL) {
      game.faults[system] = true;
      log.push({
        key: 'day',
        amount: 0,
        note: FAULT_NAMES[system] + ' has failed: it is only running at ' +
              Math.round(outputFactor(system) * 100) + '%'
      });
      /* Queue the emergency scenario for this system. script.js picks
         it up at the start of the next day and puts it in front of the
         schedule, because a dead life-support system outranks a routine
         resupply run. */
      if (!game.pendingEmergency) { game.pendingEmergency = system; }
    }
  }
  return log;
}

/* The systems that wear, and what they are called when they break. */
var MAINT_SYSTEMS = ['solar', 'oxygen', 'water', 'food', 'habitat'];
var FAULT_NAMES = {
  solar: 'The solar array',
  oxygen: 'The oxygen scrubber',
  water: 'The water recycler',
  food: 'Hydroponics',
  habitat: 'The habitat'
};

/* Servicing a structure also puts that system back to new, which is
   what makes the depot worth building. */
function serviceSystem(system) {
  if (!game || !game.maint || !(system in game.maint)) { return false; }
  game.maint[system] = MAINT_START;
  if (game.faults) { delete game.faults[system]; }
  return true;
}

/* Which maintained system a structure type corresponds to. */
var SERVICE_SYSTEM = {
  solar: 'solar',
  oxygen: 'oxygen',
  water: 'water',
  food: 'food',
  habitat: 'habitat'
};

/* ------------------------------------------------------------
   5. THE DAILY SURVIVAL CYCLE
   The day's balance is worked out once, here, and used twice: once to
   run the day, and once in the pre-flight projection, so the number
   the player is shown before launch is the number they get.
   ------------------------------------------------------------ */

/* What the site and the base do to a single day's numbers, before any
   mission event and before wear is applied. Pure calculation: it reads
   the base and the site and returns deltas, and changes nothing. */
function projectedDailyDeltas(caps, factors) {
  var crew = (typeof crewAlive === 'function') ? crewAlive() : STARTING_CREW;
  var crewFactor = crew / STARTING_CREW;

  var mods = missionMods();
  var day = missionDay();

  /* ---- power ---- */
  var solar = caps.solar * factors.sun * (mods.solarFactor || 1);
  if (day < (mods.solarFactorUntilDay || 0)) {
    solar = solar * (mods.stormSolarFactor || 1);
  }
  /* More arrays also means more surface to keep clean. */
  var solarDustLoss = caps.solarPanels * factors.dust * 0.6;
  solar = solar * (1 - Math.min(0.6, solarDustLoss / Math.max(1, caps.solar)));

  var powerUse = DAILY_POWER_USE + factors.heating + caps.solarPanels * 0.5;

  /* ---- oxygen: the crew breathes, the scrubber cleans ---- */
  var oxygen = caps.oxygen * outputFactor('oxygen') + (mods.oxygenProduction || 0);
  oxygen -= DAILY_OXYGEN_USE * crewFactor;

  /* ---- water: drinking, washing and the crops, less what the
         recycler and the ice give back ---- */
  var water = (caps.water * outputFactor('water') + factors.iceWater) +
              (mods.waterRecovery || 0);
  water -= DAILY_WATER_USE * crewFactor;

  /* ---- food: what is grown, less what is eaten ---- */
  var food = caps.food * outputFactor('food') + (mods.foodProduction || 0);
  food -= (DAILY_FOOD_USE + (mods.extraFoodUse || 0)) * crewFactor;

  /* ---- health: a habitat lets the crew recover a little ---- */
  var health = caps.health * outputFactor('habitat');

  /* A crew with no habitat cannot rest properly, and a crew with no
     console is slower to notice trouble, so both cost health. */
  if (!caps.hasHabitat) { health -= 4; }
  if (!caps.hasConsole) { health -= 1; }

  return {
    power: solar - powerUse,
    oxygen: oxygen,
    water: water,
    food: food,
    health: health,
    /* kept for the report screen, not applied to a bar */
    solarGenerated: solar,
    powerUsed: powerUse,
    heating: factors.heating,
    dustLoss: solarDustLoss
  };
}

/* The pre-flight projection uses the caps and factors the base is
   about to launch with, so it is a forecast and not a result. The
   layout comes from missionLayout(), which is already the builder's
   while the builder is open, so only the site has to be borrowed. */
function missionProjectedDaily() {
  if (!game) { game = createNewGame(); }

  var savedZone = game.zoneId;
  var zone = (typeof selectedZone === 'function') ? selectedZone() : null;
  if (zone) { game.zoneId = zone.id; }

  var result = projectedDailyDeltas(baseCapabilities(), siteFactors());

  game.zoneId = savedZone;

  return result;
}

/* ------------------------------------------------------------
   6. DUST STORMS
   Real science underneath: lunar dust is jagged, clingy and
   electrostatically charged, and electrostatic charging is why it
   clings to everything a spacesuit touches. Dust is genuinely one of
   the hardest problems for a lunar base, and it is genuinely worse at
   some sites than others.
   ------------------------------------------------------------ */

/* A dustier site meets more storms. The return is the day the storm
   starts, or 0 if this site does not get one that day. */
function stormDays() {
  var factors = siteFactors();
  var days = [];

  if (factors.dust >= 0.75) { days.push(10); }
  if (factors.dust >= 0.55) { days.push(10); }
  if (factors.dust >= 0.45) { days.push(10); }

  /* The dustiest sites get a second, earlier storm. */
  if (factors.dust >= 0.75) { days.push(5); }

  return days;
}

function isDustStormDay(day) {
  return stormDays().indexOf(day) >= 0;
}

/* How long a storm lasts, and how much of the array it leaves
   working. GAME ESTIMATE, but scaled by how dusty the site is. */
function applyDustStorm() {
  var factors = siteFactors();
  var length = (factors.dust >= 0.75) ? 3 : 2;
  var severity = (factors.dust >= 0.75) ? 0.3 : (factors.dust >= 0.55 ? 0.45 : 0.6);

  game.mods.stormSolarFactor = severity;
  game.mods.solarFactorUntilDay = game.day + length;
  game.storms = (game.storms || 0) + 1;

  return {
    length: length,
    severity: severity
  };
}

/* ------------------------------------------------------------
   7. EXPLORATION TASKS
   The two science objectives are not decided by a choice in a panel.
   They are earned by walking the base and looking at it, which is the
   one thing the 2D world can do that a list of buttons cannot.
   ------------------------------------------------------------ */

/* How many structure readouts the crew must log at THIS site. Phase 4
   makes that depend on the verified ice record: a crater where water
   was actually measured is a better place to do science, so the survey
   is signed off sooner. Anywhere else it is the usual four. */
function missionSurveyTarget() {
  if (typeof surveyTargetFor === 'function' && game && game.zoneId) {
    return surveyTargetFor(game.zoneId);
  }
  return (typeof SURVEY_TARGET === 'number') ? SURVEY_TARGET : 4;
}

function noteExploration() {
  if (!game) { return; }

  if (game.explored >= EXPLORE_TARGET) { game.completed['obj-explore'] = true; }
  if (Object.keys(game.surveyed || {}).length >= missionSurveyTarget()) {
    game.completed['obj-survey'] = true;
  }
}

/* A structure type has been inspected by the crew. */
function noteSurvey(type) {
  if (!game || !type) { return; }
  if (!game.surveyed) { game.surveyed = {}; }
  game.surveyed[type] = true;
  noteExploration();
}

/* ------------------------------------------------------------
   8. STATE SAFETY
   Nothing in this file, and nothing in script.js, is allowed to leave
   the mission in an impossible state. These are the rules, and
   `sanitizeMission` is the single place they are enforced.
   ------------------------------------------------------------ */

function sanitizeMission() {
  if (!game) { return game; }

  var keys = ['oxygen', 'water', 'food', 'power', 'health'];
  for (var i = 0; i < keys.length; i++) {
    var key = keys[i];
    var v = game[key];
    /* A value that is not a real number at all is replaced rather than
       propagated, because NaN would silently poison every comparison
       after it. */
    if (typeof v !== 'number' || !isFinite(v)) { v = 0; }
    game[key] = round1(clamp(v, 0, MAX_VALUE));
  }

  if (game.maint) {
    for (var s = 0; s < MAINT_SYSTEMS.length; s++) {
      var sys = MAINT_SYSTEMS[s];
      var c = game.maint[sys];
      if (typeof c !== 'number' || !isFinite(c)) { c = 0; }
      game.maint[sys] = round1(clamp(c, 0, MAINT_START));
    }
  }

  /* The day counter is the one number that must not be clamped: going
     past the limit is exactly how the limit is detected. It is only
     ever allowed to go one past. */
  if (typeof game.day !== 'number' || !isFinite(game.day) || game.day < 1) {
    game.day = 1;
  }

  /* An objective may only be marked done if the objective exists, so a
     stray key can never inflate the score. */
  for (var id in game.completed) {
    if (Object.prototype.hasOwnProperty.call(game.completed, id)) {
      if (!isRealObjective(id)) { delete game.completed[id]; }
    }
  }

  /* A finished mission can never be unfinished again, and a success can
     never be revoked. Every path into endMission goes through here. */
  if (game.day > MISSION_LENGTH_DAYS && game.success) {
    game.success = false;
    game.failReason = 'Mission time ran out before every objective was completed.';
  }

  return game;
}

function isRealObjective(id) {
  /* Phase 5: the list is no longer just the eight in script.js. The
     optional objectives in challenges.js have to count too, or they
     could never be marked done at all - and sanitizeMission() would
     quietly delete every one of them. */
  var list = (typeof allObjectives === 'function') ? allObjectives() : OBJECTIVES;
  for (var i = 0; i < list.length; i++) {
    if (list[i].id === id) { return true; }
  }
  return false;
}

